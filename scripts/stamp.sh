#
#   ./scripts/stamp.sh
#
# The file list and order below MUST stay identical to panel.js's
# FINGERPRINT_FILES — same paths, same order, same "concatenate raw bytes,
# SHA-256, first 7 hex chars" — or the two hashes are not comparable.

